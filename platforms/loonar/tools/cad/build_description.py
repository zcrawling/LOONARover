#!/usr/bin/env python3
"""Build runtime mount frames from the checked-in STEP extraction.

CAD-origin frames are explicitly suffixed _cad; sensor origins are separately
parameterized. No estimator, encoder calibration, or live TF is modified.
"""
import json
from pathlib import Path
import warnings
import numpy as np
from scipy.spatial.transform import Rotation

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT/'ros2/loonar_description'

def main():
    data = json.loads((ROOT/'hardware/tf/cad_frames.json').read_text())
    frames = {r['frame']:r for r in data['frames']}
    # CAD +Y points forward (tail at -Y), CAD -X is robot left, +Z is up.
    # Wheel bore axes pass through CAD z=57 mm, y=0 in both occurrences.
    T = np.eye(4)
    T[:3,:3] = [[0,1,0],[-1,0,0],[0,0,1]]
    T[:3,3] = [0,0,-.057]
    names = {19050:'left_motor_cad',19051:'chassis_cad',19052:'right_motor_cad',
             19053:'reaction_wheel_assembly_cad',19054:'battery_cad',19055:'tail_mount_cad',
             19056:'motor_driver_cad',19057:'reaction_esc_cad',19058:'raspberry_pi_cad',
             19059:'tof_assembly_cad',19060:'camera_assembly_cad',19061:'sensor_mcu_cad',
             19062:'motor_bracket_cad'}
    rows=[]
    for occurrence,name in names.items():
        r=frames[f'cad_root_o{occurrence}']; m=T@np.array(r['root_matrix'])
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            rpy=Rotation.from_matrix(m[:3,:3]).as_euler('xyz').tolist()
        rows.append(dict(name=name,xyz_m=m[:3,3].tolist(),rpy_rad=rpy,source_occurrence=occurrence))
    config=dict(source=data['source'],sha256=data['sha256'],cad_to_base=T.tolist(),mounts=rows,
                imu=dict(rotation_status='user_confirmed_2026-10-06',rpy_rad=[0,0,float(np.pi/2)],
                         position_status='nominal_floor_reference_not_measured_chip_center',
                         xyz_m=[.03575,0,-.057],note='ToF-underfloor centre. CAD floor datum z=0 assumed; floor thickness + board/chip height must be measured.'),
                tof=dict(position_status='CAD_MS22MF005-B_component_origin_not_calibrated_optical_center',
                         xyz_m=[.03575,.0000500000471,-.0075],rpy_rad=[0,0,0]),
                camera=dict(position_status='assembly_origin_only_optical_offset_unmeasured'),
                wheel_note='spindle origins, not tyre contact centres; do not use 0.257 m as encoder track calibration',
                inactive_cad_occurrence=19063)
    (OUT/'config/cad_mounts.json').write_text(json.dumps(config,ensure_ascii=False,indent=2)+'\n')
    text=['<?xml version="1.0"?>','<!-- GENERATED by tools/cad/build_description.py; edit generator/configuration, not this file. -->',
          '<robot xmlns:xacro="http://www.ros.org/wiki/xacro" name="loonar">',
          '<xacro:arg name="imu_xyz" default="0.03575 0 -0.057"/>',
          '<xacro:arg name="imu_rpy" default="0 0 1.5707963267948966"/>',
          '<xacro:arg name="tof_xyz" default="0.03575 0.0000500000471 -0.0075"/>',
          '<xacro:arg name="tof_rpy" default="0 0 0"/>',
          '<xacro:arg name="publish_optical_frames" default="false"/>',
          '<xacro:arg name="tof_optical_offset" default="0 0 0"/>',
          '<xacro:arg name="camera_optical_xyz" default="0 0 0"/>',
          '<xacro:arg name="camera_optical_rpy" default="0 0 0"/>',
          '<link name="base_link"/>']
    def fixed(parent,child,xyz,rpy):
        return f'<link name="{child}"/><joint name="{child}_mount" type="fixed"><parent link="{parent}"/><child link="{child}"/><origin xyz="{xyz}" rpy="{rpy}"/></joint>'
    fmt=lambda v:' '.join(f'{x:.12g}' for x in v)
    for r in rows: text.append(fixed('base_link',r['name'],fmt(r['xyz_m']),fmt(r['rpy_rad'])))
    text.extend([fixed('base_link','imu_link','$(arg imu_xyz)','$(arg imu_rpy)'),
                 fixed('base_link','tof_link','$(arg tof_xyz)','$(arg tof_rpy)'),
                 '<!-- Optical frames require explicit measured offsets; disabled by default. -->',
                 '<xacro:if value="$(arg publish_optical_frames)">',
                 fixed('tof_link','tof_optical_frame','$(arg tof_optical_offset)','-1.5707963267948966 0 -1.5707963267948966'),
                 fixed('camera_assembly_cad','camera_optical_frame','$(arg camera_optical_xyz)','$(arg camera_optical_rpy)'),
                 '</xacro:if>'])
    for side,y in [('left',.1285),('right',-.1285)]:
        text.append(fixed('base_link',side+'_wheel_spindle',f'0 {y} 0','0 0 0'))
        text.append(f'<link name="{side}_wheel_link"/><joint name="{side}_wheel_joint" type="continuous"><parent link="{side}_wheel_spindle"/><child link="{side}_wheel_link"/><origin xyz="0 0 0" rpy="0 0 0"/><axis xyz="0 1 0"/></joint>')
    text.append('</robot>')
    (OUT/'urdf/loonar.urdf.xacro').write_text('\n'.join(text)+'\n')

if __name__=='__main__':main()
